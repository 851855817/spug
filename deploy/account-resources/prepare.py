"""Generate frozen additions offline against verified production migration code.

This command never connects to a database, starts services, or publishes files.
Outputs without --scope are explicitly provisional, for isolated rehearsal only.
"""
import argparse
import ast
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys


HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('account_resource_contract', HERE / 'contract.py')
contract = importlib.util.module_from_spec(spec)
spec.loader.exec_module(contract)
require = contract.require


def stage_history(history, target, expected):
    history, target = Path(history), Path(target)
    names = {'apps/%s/migrations/%s.py' % tuple(node.split('/')) for node in expected}
    actual = {p.relative_to(history).as_posix() for p in history.glob('apps/*/migrations/*.py')
              if p.name != '__init__.py'}
    require(actual == names, 'history-file-set-not-exact')
    contents = {}
    for node, proof in sorted(expected.items()):
        app, name = node.split('/')
        relative = 'apps/%s/migrations/%s.py' % (app, name)
        source = history / relative
        require(source.is_file() and not any(p.is_symlink() for p in (source, *source.parents)),
                'history-linked-or-missing')
        data = source.read_bytes()
        require(len(data) < 512 * 1024 and hashlib.sha256(data).hexdigest() == proof['sha256'],
                'history-content-mismatch')
        tree = ast.parse(data)
        require(not any(isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute)
                        and n.func.attr in ('RunPython', 'RunSQL') for n in ast.walk(tree)),
                'history-data-operation-requires-separate-review')
        contents[relative] = data
    # All inputs pass validation before creating even a partial destination.
    for relative, data in contents.items():
        destination = target / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        require(not destination.exists(), 'history-destination-occupied')
        destination.write_bytes(data)
        (destination.parent / '__init__.py').write_bytes(b'')


def generate(source):
    sys.dont_write_bytecode = True
    sys.path.insert(0, str(source))
    os.environ['DJANGO_SETTINGS_MODULE'] = 'spug.test_settings'
    import django
    django.setup()
    from django.apps import apps
    from django.db.migrations.autodetector import MigrationAutodetector
    from django.db.migrations.loader import MigrationLoader
    from django.db.migrations.questioner import NonInteractiveMigrationQuestioner
    from django.db.migrations.state import ProjectState
    from django.db.migrations.writer import MigrationWriter
    from apps.account.resource_schema import verify_legacy_models
    from apps.account.resource_migration import ADDITIVE_MODELS
    verify_legacy_models(source / 'apps')
    require(set(ADDITIVE_MODELS) == {(app, name.lower()) for app, models in contract.MODELS.items()
                                   for name in models}, 'registered-additions-not-exact')
    loader = MigrationLoader(None, ignore_no_migrations=True)
    observed = {}
    for key, node in sorted(loader.graph.node_map.items()):
        path = source / 'apps' / key[0] / 'migrations' / (key[1] + '.py')
        observed['/'.join(key)] = {'parents': sorted('/'.join(parent.key) for parent in node.parents),
                                   'sha256': contract.sha(path.read_bytes())}
    require(observed == contract.BASELINE['migration_graph'], 'loaded-history-graph-not-exact')
    changes = MigrationAutodetector(loader.project_state(), ProjectState.from_apps(apps),
        NonInteractiveMigrationQuestioner()).changes(graph=loader.graph, migration_name='account_resources')
    files = {}
    for app, migrations in changes.items():
        for migration in migrations:
            migration.dependencies = sorted(migration.dependencies)
            path = 'apps/%s/migrations/%s.py' % (app, migration.name)
            files[path] = re.sub(r'^# Generated by Django .*\n',
                '# Frozen account-resources migration; production graph is pinned.\n',
                MigrationWriter(migration).as_string(), count=1)
    facts = contract.validate_migrations(files)
    for name, content in files.items():
        (source / name).write_text(content, encoding='utf-8', newline='\n')
    print(json.dumps(facts, sort_keys=True))


def prepare(source, history, output, scope=None):
    require(not output.exists(), 'preparation-output-already-exists')
    require(source.is_dir() and (source / 'apps/account/resource_model_contract.json').is_file(),
            'candidate-source-invalid')
    require(not (source / 'spug/overrides.py').exists(), 'candidate-source-must-exclude-overrides')
    staged = output / 'source/spug_api'
    input_hashes = {}
    for path in sorted(source.rglob('*')):
        if not path.is_file() or path.suffix not in ('.py', '.json'):
            continue
        relative = path.relative_to(source)
        if any(part in ('migrations', '__pycache__', 'storage', 'logs', 'repos') for part in relative.parts):
            continue
        require(not any(p.is_symlink() for p in (path, *path.parents)), 'candidate-source-linked')
        data = path.read_bytes().replace(b'\r\n', b'\n')
        input_hashes[relative.as_posix()] = contract.sha(data)
        destination = staged / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(data)
    if scope is not None:
        require(scope['profile'] == contract.PROFILE and
                scope['previous_revision'] == contract.BASELINE['previous_revision'], 'scope-baseline-mismatch')
        for name, value in scope['files'].items():
            if name.startswith('spug_api/'):
                require(input_hashes.get(name[len('spug_api/'):]) == value['sha256'], 'scope-source-mismatch')
    stage_history(history, staged, contract.BASELINE['migration_graph'])
    result = subprocess.check_output([sys.executable, str(HERE / 'prepare.py'), '--generate', str(staged)],
                                     env=dict(os.environ, PYTHONDONTWRITEBYTECODE='1'), text=True, timeout=90)
    facts = json.loads(result.strip())
    require(facts == json.loads((HERE / 'migration-plan.json').read_text()), 'generated-migrations-not-reviewed')
    if scope is not None:
        candidate, rollback = contract.dockerfiles(scope['revision'], facts,
            {name[len('spug_api/'):]: value['sha256'] for name, value in scope['files'].items()
             if name.startswith('spug_api/')})
        (output / 'Dockerfile').write_text(candidate, newline='\n')
        (output / 'rollback.Dockerfile').write_text(rollback, newline='\n')
    manifest = {'profile': contract.PROFILE, 'previous_revision': contract.BASELINE['previous_revision'],
                'revision': scope['revision'] if scope else None, 'provisional': scope is None,
                'input_api_sha256': input_hashes, 'migrations': facts,
                'baseline_image_id': contract.BASELINE['image_id'],
                'baseline_metadata_sha256': contract.sha((HERE / 'production-baseline.json').read_bytes())}
    (output / 'migration-manifest.json').write_text(json.dumps(manifest, indent=2, sort_keys=True) + '\n')
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=HERE.parents[1] / 'spug_api')
    parser.add_argument('--history-root', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--scope', type=Path)
    args = parser.parse_args()
    manifest = prepare(args.source, args.history_root, args.output,
                       json.loads(args.scope.read_text()) if args.scope else None)
    print(json.dumps({'profile': contract.PROFILE, 'provisional': manifest['provisional'],
                      'migration_files': len(manifest['migrations']), 'output': str(args.output)}))


if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[1] == '--generate':
        generate(Path(sys.argv[2]).resolve())
    else:
        main()
