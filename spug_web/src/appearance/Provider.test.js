import React from 'react';
import ReactDOM from 'react-dom';
import { act } from 'react-dom/test-utils';
import AppearanceProvider from './Provider';
import { createAppearanceStore } from './store';
import { ConfigProvider } from 'antd';
jest.mock('antd',()=>({ConfigProvider:{config:jest.fn()}}));
let container,request,store,properties;
const flush=async()=>{for(let i=0;i<15;i++)await Promise.resolve();};
const result=preset=>({ok:true,status:200,json:async()=>({data:{version:1,preset,revision:'a'.repeat(32)}})});
beforeEach(()=>{jest.useFakeTimers();localStorage.clear();container=document.createElement('div');document.body.appendChild(container);
  Object.defineProperty(document,'visibilityState',{configurable:true,value:'visible'});
  properties=jest.spyOn(document.documentElement.style,'setProperty');
  request=jest.fn().mockResolvedValue(result('night'));store=createAppearanceStore(request);});
afterEach(()=>{act(()=>{ReactDOM.unmountComponentAtNode(container);});container.remove();jest.useRealTimers();jest.clearAllMocks();jest.restoreAllMocks();});
test('global root applies persisted palette and polls once per visible minute with cleanup',async()=>{
  await act(async()=>{ReactDOM.render(<AppearanceProvider store={store}><span>页面</span></AppearanceProvider>,container);await flush();});
  expect(document.documentElement.dataset.kopsTheme).toBe('night');
  expect(properties).toHaveBeenCalledWith('--kops-surface','#172234');
  expect(ConfigProvider.config).toHaveBeenLastCalledWith({theme:expect.objectContaining({primaryColor:'#60A5FA'})});
  expect(request).toHaveBeenCalledTimes(1);
  await act(async()=>{jest.advanceTimersByTime(60000);await flush();});expect(request).toHaveBeenCalledTimes(2);
  Object.defineProperty(document,'visibilityState',{value:'hidden'});
  act(()=>{document.dispatchEvent(new Event('visibilitychange'));});
  await act(async()=>{jest.advanceTimersByTime(120000);await flush();});expect(request).toHaveBeenCalledTimes(2);
  request.mockResolvedValue(result('jade'));Object.defineProperty(document,'visibilityState',{value:'visible'});
  await act(async()=>{document.dispatchEvent(new Event('visibilitychange'));await flush();});
  expect(request).toHaveBeenCalledTimes(3);expect(document.documentElement.dataset.kopsTheme).toBe('jade');
  act(()=>{ReactDOM.unmountComponentAtNode(container);});
  await act(async()=>{jest.advanceTimersByTime(60000);await flush();});expect(request).toHaveBeenCalledTimes(3);
});
